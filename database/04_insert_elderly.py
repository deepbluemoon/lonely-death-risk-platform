# =========================================================
# 숫자 변환
# =========================================================

def to_number(value):

    if value is None:
        return None

    value = str(value).strip()

    if value == "":
        return None

    value = value.replace(
        ",",
        ""
    )

    try:
        return float(value)

    except ValueError:
        return None


# =========================================================
# CSV 적재
# =========================================================

def insert_elderly():

    print(
        "======================================"
    )

    print(
        "고령인구 데이터 적재 시작"
    )

    print(
        "======================================"
    )


    # -----------------------------------------------------
    # CSV 존재 확인
    # -----------------------------------------------------

    if not os.path.exists(CSV_PATH):

        print(
            "CSV 파일을 찾을 수 없습니다."
        )

        print(
            f"경로: {CSV_PATH}"
        )

        return


    # -----------------------------------------------------
    # CSV 읽기
    # -----------------------------------------------------

    rows = []


    with open(
        CSV_PATH,
        "r",
        encoding="utf-8-sig",
        newline=""
    ) as file:

        reader = csv.DictReader(
            file
        )

        print(
            "CSV 컬럼 확인:"
        )

        print(
            reader.fieldnames
        )


        for row in reader:

            region = normalize_region(
                    row["Region"]
                )

            y2019 = to_number(
                    row["2019_Average"]
                )

            y2020 = to_number(
                    row["2020_Average"]
                )

            y2021 = to_number(
                    row["2021_Average"]
                )


            rows.append(
                (
                    region,
                    y2019,
                    y2020,
                    y2021
                )
            )


    # -----------------------------------------------------
    # Oracle 연결
    # -----------------------------------------------------

    conn = connect_db()

    cursor = conn.cursor()


    print(
        "Oracle DB 연결 성공!"
    )


    # -----------------------------------------------------
    # 기존 데이터 삭제
    #
    # CSV 전체를 다시 넣는 방식이므로
    # 중복 방지를 위해 먼저 삭제
    # -----------------------------------------------------

    cursor.execute(
        """
        DELETE FROM TBL_ELDERLY_POPULATION
        """
    )


    # -----------------------------------------------------
    # 전체 CSV 적재
    # -----------------------------------------------------

    cursor.executemany(
        """
        INSERT INTO TBL_ELDERLY_POPULATION
        (
            REGION,
            Y2019_AVERAGE,
            Y2020_AVERAGE,
            Y2021_AVERAGE
        )
        VALUES
        (
            :1,
            :2,
            :3,
            :4
        )
        """,
        rows
    )


    conn.commit()


    # -----------------------------------------------------
    # 결과 출력
    # -----------------------------------------------------

    for row in rows:

        print(
            f"적재 완료: {row[0]}"
        )


    cursor.close()
    conn.close()


    print()
    print(
        "======================================"
    )

    print(
        "고령인구 데이터 적재 완료"
    )

    print(
        "======================================"
    )


# =========================================================
# 실행
# =========================================================

if __name__ == "__main__":

    insert_elderly()